function cleanInlineText(text: string) {
  return text.replace(/\*\*/g, "").replace(/\*/g, "");
}

function renderBrandText(text: string, keyPrefix: string): ReactNode[] {
  const regex = /(BIGBEANS DIGITAL|Blog)/g;
  const parts: ReactNode[] = [];
  let lastIndex = 0;
  let counter = 0;
  let match: RegExpExecArray | null;

  while ((match = regex.exec(text)) !== null) {
    if (match.index > lastIndex) {
      parts.push(<span key={`${keyPrefix}-${counter++}`}>{text.slice(lastIndex, match.index)}</span>);
    }

    const matchedText = match[0];
    parts.push(
      <Link
        key={`${keyPrefix}-${counter++}`}
        href={matchedText === "Blog" ? "/blog" : "/"}
        className="font-medium text-[#171717] underline decoration-[#F8BC04] decoration-2 underline-offset-4 transition-colors hover:text-[#F8BC04]"
      >
        {matchedText}
      </Link>
    );

    lastIndex = regex.lastIndex;
  }

  if (lastIndex < text.length) {
    parts.push(<span key={`${keyPrefix}-${counter++}`}>{text.slice(lastIndex)}</span>);
  }

  return parts;
}

function renderInlineText(text: string): ReactNode {
  const markdownLinkRegex = /\[([^\]]+)\]\(([^)]+)\)/g;
  const parts: ReactNode[] = [];
  let lastIndex = 0;
  let match: RegExpExecArray | null;
  let counter = 0;

  while ((match = markdownLinkRegex.exec(text)) !== null) {
    if (match.index > lastIndex) {
      parts.push(...renderBrandText(cleanInlineText(text.slice(lastIndex, match.index)), `a-${counter++}`));
    }

    const label = cleanInlineText(match[1]);
    const href = match[2].includes("bigbeansdigital.com") ? "/" : match[2];

    parts.push(
      <Link
        key={`link-${counter++}`}
        href={href}
        className="font-medium text-[#171717] underline decoration-[#F8BC04] decoration-2 underline-offset-4 transition-colors hover:text-[#F8BC04]"
      >
        {label}
      </Link>
    );

    lastIndex = markdownLinkRegex.lastIndex;
  }

  if (lastIndex < text.length) {
    parts.push(...renderBrandText(cleanInlineText(text.slice(lastIndex)), `b-${counter++}`));
  }

  return parts.length ? parts : cleanInlineText(text);
}

function makeId(title: string) {
  return title.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
}

function PolicyContent({ content }: { content: string }) {
  return (
    <div>
      {content.split("\n").map((line, index) => {
        const trimmed = line.trim();

        if (!trimmed || trimmed === "---") {
          return <div key={index} className={trimmed === "---" ? "my-7 h-px bg-gray-200 sm:my-9" : "h-3"} />;
        }

        if (trimmed.startsWith("# ")) {
          const title = trimmed.slice(2);
          return (
            <h2
              key={index}
              id={title === "PRIVACY POLICY" ? "privacy-policy" : makeId(title)}
              className="scroll-mt-24 mb-5 mt-8 text-xl font-black leading-tight tracking-[-0.02em] text-[#171717] first:mt-0 sm:mb-6 sm:mt-10 sm:text-2xl"
            >
              {cleanInlineText(title)}
            </h2>
          );
        }

        if (trimmed.startsWith("## ")) {
          return (
            <h3 key={index} className="mb-3 mt-7 text-[17px] font-bold leading-snug text-[#171717] sm:mt-8 sm:text-[19px]">
              {renderInlineText(trimmed.slice(3))}
            </h3>
          );
        }

        if (trimmed.startsWith("### ")) {
          return (
            <h4 key={index} className="mb-2 mt-6 text-[15px] font-bold leading-snug text-[#171717] sm:text-[17px]">
              {renderInlineText(trimmed.slice(4))}
            </h4>
          );
        }

        const isList = /^[a-z]\.\s/i.test(trimmed) || /^\d+\.\s/.test(trimmed);

        return (
          <p key={index} className={`text-[13px] leading-6 text-gray-600 sm:text-[14px] sm:leading-7 ${isList ? "pl-2" : ""}`}>
            {renderInlineText(trimmed)}
          </p>
        );
      })}
    </div>
  );
}

